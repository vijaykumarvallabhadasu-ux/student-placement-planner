-- 2. Create STUDENTS table
CREATE TABLE students (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) UNIQUE NOT NULL,
    password_hash VARCHAR2(64) NOT NULL,
    role VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL,
    department VARCHAR2(60) DEFAULT 'CSE',
    year_of_study NUMBER(2) DEFAULT 4,
    cgpa NUMBER(3,2) DEFAULT 7.5,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_student_role CHECK (role IN ('STUDENT', 'ADMIN'))
);

-- 3. Create JOBS table (supporting full eligibility, CGPA, and deadline)
CREATE TABLE jobs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(150) NOT NULL,
    company VARCHAR2(150) NOT NULL,
    location VARCHAR2(100) DEFAULT 'On-Site',
    description VARCHAR2(1000),
    eligibility VARCHAR2(150) DEFAULT 'All Engineering Branches',
    min_cgpa NUMBER(3,2) DEFAULT 0.0,
    deadline DATE,
    created_at DATE DEFAULT SYSDATE NOT NULL
);

-- 4. Create SKILLS table
CREATE TABLE skills (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    skill_name VARCHAR2(100) NOT NULL,
    proficiency VARCHAR2(30) DEFAULT 'Proficient',
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_student_skill UNIQUE (student_id, skill_name)
);

-- 5. Create TASKS table
CREATE TABLE tasks (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    task_title VARCHAR2(200) NOT NULL,
    due_date DATE,
    status VARCHAR2(20) DEFAULT 'Pending' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_task_status CHECK (status IN ('Pending', 'Completed'))
);

-- 6. Create APPLICATIONS table (linking students and jobs)
CREATE TABLE applications (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    job_id NUMBER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    status VARCHAR2(30) DEFAULT 'APPLIED' NOT NULL,
    applied_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_student_job UNIQUE (student_id, job_id)
);

